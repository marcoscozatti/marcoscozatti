export const LANG_LABELS = { pt: 'PT', en: 'EN', es: 'ES' };

export function t(lang, key) {
  return (UI_STRINGS[lang] && UI_STRINGS[lang][key]) || UI_STRINGS.pt[key] || key;
}

/** Pega campo multilíngue de uma linha do banco, com fallback para PT. */
export function pickLang(row, field, lang) {
  if (!row) return '';
  const value = row[`${field}_${lang}`];
  if (value && String(value).trim() !== '') return value;
  return row[`${field}_pt`] || '';
}
